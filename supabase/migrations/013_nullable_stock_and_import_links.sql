-- ============================================================
-- BIZIM final-mvp — честный "нет данных" для остатков + связи импорта
-- Выполнить ПОСЛЕ 012_nullable_order_prices.sql.
--
-- current_stock/min_stock были NOT NULL с дефолтом 0 — значит любой товар,
-- созданный автоматически при импорте продаж без колонки остатка, тут же
-- показывал "Остаток: 0" вместо честного "нет данных". Теперь оба поля
-- nullable: NULL = "не указано", а не "ноль на складе". Формы ручного
-- добавления по-прежнему пишут туда то число, которое ввёл пользователь
-- (включая осознанный 0) — это не затронуто.
--
-- Также добавляет category как nullable (раньше NOT NULL default 'Общее' —
-- сам по себе не "придуманная метрика", но раз уж выравниваем схему под
-- честный источник данных, оставляем текстовые поля с нейтральным
-- дефолтом и делаем его необязательным для явного контроля через импорт).
-- ============================================================

alter table public.inventory_items
  alter column current_stock drop not null,
  alter column current_stock drop default,
  alter column min_stock drop not null,
  alter column min_stock drop default;
