// Общий маркер для потокового /api/chat: сервер дописывает его в конец
// потока, если ошибка (например обрыв связи с OpenAI) случилась уже ПОСЛЕ
// того как в ответ ушла часть текста. \u0000 практически невозможен в
// обычном тексте ответа модели, поэтому безопасен как разделитель.
// Вынесено в отдельный модуль, чтобы route.ts (сервер) и ChatWindow.tsx
// (клиент) использовали ровно одну и ту же строку и не разъехались.
export const STREAM_ERROR_MARKER = "\u0000BIZIM_STREAM_ERROR\u0000";

// Аналогичный маркер, но для УСПЕШНОГО завершения стрима: сервер дописывает
// его в конец потока вместе с JSON-метаданными (реальные id сохранённых
// сообщений в Supabase, обновлённый заголовок диалога) — стриминг остаётся
// простым текстовым потоком (без SSE/WebSocket), но клиент всё равно
// получает структурированные данные без отдельного round-trip после стрима.
export const STREAM_META_MARKER = "\u0000BIZIM_STREAM_META\u0000";

export interface StreamMeta {
  conversationId: string;
  userMessageId?: string;
  modelMessageId: string;
  title?: string;
  appended?: boolean;
}
